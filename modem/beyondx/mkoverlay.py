#!/usr/bin/env python3
"""Build zrn-modem-overlay.dts from the S10 5G's live device tree
(stock/live/beyondx-twrp-boot.dts): the CP mailbox (mailbox_cp), the shared
memory's layout (shmem), the LTE modem interface (mif_pdata, S5000AP) and the
5G one (mif2_pdata, S5100 on PCIe) with their io devices, and a node of our
own for the S5100's control pins (zrn_s5100_gpio.c: CMGP EINT lines of gpm30
and gpm28, GIC SPI 0x73 and 0x71 as stock's pin controller).
Dropped: phandles, pin control and gpios (pin controller references of the
stock tree; the S5100's pins are looked up by name in zrn_s5100_gpio.c). Changed: u32 cells that dtc printed as strings back to cells;
interrupt type 0, which the stock GIC driver took as its
default, to level high (4), which mainline's needs; the children of "iodevs"
in reverse, because applying an overlay prepends each new node to its parent's
list: so the kernel sees the io devices in stock's order, which the shared
memory ring layout relies on (IPC channels first, packet data last:
ps_channel_start in link_device_memory_sbd.c)."""
import re, sys, os

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '../../stock/live/beyondx-twrp-boot.dts')).read().split('\n')

def node(header, must=None):
    for i, l in enumerate(src):
        if l.strip() == header + ' {' and (must is None or any(must in x for x in src[i:i + 4])):
            depth, out = 0, []
            for l2 in src[i:]:
                depth += l2.count('{') - l2.count('}')
                out.append(l2)
                if depth == 0:
                    return out
    sys.exit('not found: ' + header)

DROP = re.compile(r'^\s*(linux,phandle|phandle|pinctrl-\d+|pinctrl-names|gpios|mif,gpio\w*|gpio_\w+)\s*=')

def reverse_iodevs(lines):
    """the child blocks of the iodevs node, last first"""
    start = next(i for i, l in enumerate(lines) if l.strip() == 'iodevs {')
    depth, blocks, cur, i = 0, [], [], start + 1
    while True:
        l = lines[i]
        if depth == 0 and l.strip() == '};':
            break
        if depth == 0 and not l.strip():
            i += 1
            continue
        cur.append(l)
        depth += l.count('{') - l.count('}')
        if depth == 0:
            blocks.append(cur)
            cur = []
        i += 1
    body = []
    for b in reversed(blocks):
        body += b + ['']
    return lines[:start + 1] + body[:-1] + lines[i:]

def clean(lines, name):
    lines = reverse_iodevs(lines) if any(l.strip() == 'iodevs {' for l in lines) else lines
    out = []
    for l in lines:
        if DROP.match(l):
            continue
        m = re.match(r'(\s*interrupts = <)(.*)(>;)', l)
        if m:
            cells = m.group(2).split()
            for k in range(2, len(cells), 3):
                if cells[k] == '0x00':
                    cells[k] = '0x04'
            l = m.group(1) + ' '.join(cells) + m.group(3)
        # dtc printed some u32 cells as strings ("\v \0" = 0x0b200000)
        m = re.match(r'(\s*[\w,-]+ = )"(.*)";$', l)
        if m and m.group(2).endswith('\\0'):
            raw = m.group(2).encode().decode('unicode_escape').encode('latin1') + b'\0'
            if len(raw) == 4:
                l = m.group(1) + '<0x%x>;' % int.from_bytes(raw, 'big')
        out.append(l)
    indent = len(out[0]) - len(out[0].lstrip('\t'))
    out = ['\t\t\t' + x[indent:] if x.strip() else x for x in out]
    out[0] = '\t\t\t' + name + ' {'
    return out

body = (clean(node('mailbox_cp'), 'mcu_ipc@15920000') + [''] +
        clean(node('shmem', 'exynos-shm_ipc'), 'shmem@F0000000') + [''] +
        clean(node('mif_pdata', '"sec_modem,modem_pdata"'), 'mif_pdata') + [''] +
        clean(node('mif2_pdata', '"sec_modem,modem2_pdata"'), 'mif2_pdata') + ['',
        '\t\t\ts5100_gpio {',
        '\t\t\t\tcompatible = "omonullos,s5100-gpio";',
        '\t\t\t\tinterrupts = <0x00 0x73 0x04 0x00 0x71 0x04>;\t/* gpm30, gpm28 */',
        '\t\t\t};'])

dts = ['/*', ' * Generated by modem/beyondx/mkoverlay.py from stock/live/beyondx-twrp-boot.dts:',
       ' * do not edit. See mkoverlay.py for what is dropped and changed.', ' */',
       '/dts-v1/;', '/plugin/;', '', '/ {', '\tfragment@0 {', '\t\ttarget-path = "/";',
       '\t\t__overlay__ {'] + body + ['\t\t};', '\t};', '};', '']
open(os.path.join(here, 'zrn-modem-overlay.dts'), 'w').write('\n'.join(dts))
