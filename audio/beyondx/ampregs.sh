#!/bin/sh
# read CS35L40 registers (32-bit addr/data) on i2c-38
rd() { set -- $(i2ctransfer -f -y 38 w4@$1 $(printf '0x%02x 0x%02x 0x%02x 0x%02x' $(( ($2>>24)&255 )) $(( ($2>>16)&255 )) $(( ($2>>8)&255 )) $(( $2&255 ))) r4 2>&1); echo "$1$2$3$4" | sed 's/0x//g'; }
for a in 0x40 0x41; do
  printf "%s:" $a
  for r in 0x2014 0x2018 0x201c 0x2024 0x2c04 0x2c0c 0x3800 0x4800 0x4808 0x4820 0x4c00 0x6000 0x6808 0x6c04 0x10010 0x10014 0x10018 0x1001c 0x10090 0x10094 0x10098 0x1009c 0x12004; do
    printf " %x=%s" $r $(rd $a $((r)))
  done; echo
done
